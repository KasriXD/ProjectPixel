#!/usr/bin/env python3
"""Vendors the parts of Luau the engine needs into third_party/luau/.

Only the libraries required to compile and run scripts are copied:
Common, Ast, Bytecode, Compiler and VM. (Analysis, CodeGen, Config,
Require and the CLI are not used.) The source lists are generated from
upstream's Sources.cmake so the build always matches the vendored files.

Usage:
    python3 tools/update_luau.py 0.743

Then: rebuild, run the full test suite, update the version in
docs/dependencies.md and third_party/VERSIONS.md, and commit.
Requires git and network access to github.com.
"""

import pathlib
import re
import shutil
import subprocess
import sys
import tempfile

REPO = "https://github.com/luau-lang/luau.git"
LIBRARIES = ["Common", "Ast", "Bytecode", "Compiler", "VM"]
ROOT = pathlib.Path(__file__).resolve().parent.parent
DEST = ROOT / "third_party" / "luau"


def run(*args, cwd=None):
    return subprocess.run(args, cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def source_lists(sources_cmake: str) -> dict:
    """Extracts the .cpp files of each target_sources(Luau.<Lib> ...) block."""
    lists = {}
    for lib in LIBRARIES:
        match = re.search(r"target_sources\(Luau\.%s PRIVATE(.*?)\)" % lib, sources_cmake, re.S)
        if not match:
            sys.exit(f"Could not find sources for Luau.{lib} in Sources.cmake")
        files = [f for f in match.group(1).split() if f.endswith(".cpp")]
        lists[lib] = files
    return lists


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    tag = sys.argv[1]
    with tempfile.TemporaryDirectory() as tmp:
        checkout = pathlib.Path(tmp) / "luau"
        run("git", "clone", "--quiet", "--depth", "1", "--branch", tag, REPO, str(checkout))
        commit = run("git", "rev-parse", "HEAD", cwd=checkout)
        lists = source_lists((checkout / "Sources.cmake").read_text())

        if DEST.exists():
            for child in DEST.iterdir():
                if child.name != "CMakeLists.txt":  # our build file is maintained by hand
                    shutil.rmtree(child) if child.is_dir() else child.unlink()
        DEST.mkdir(parents=True, exist_ok=True)
        for lib in LIBRARIES:
            shutil.copytree(checkout / lib, DEST / lib)
        shutil.copy(checkout / "LICENSE.txt", DEST / "LICENSE.txt")
        shutil.copy(checkout / "lua_LICENSE.txt", DEST / "lua_LICENSE.txt")

    lines = [
        "# Generated by tools/update_luau.py from upstream Sources.cmake - do not edit.",
        f'set(PX_LUAU_VERSION "{tag}")',
        f'set(PX_LUAU_COMMIT "{commit}")',
    ]
    for lib in LIBRARIES:
        lines.append(f"set(PX_LUAU_{lib.upper()}_SOURCES")
        lines += [f"    {f}" for f in lists[lib]]
        lines.append(")")
    (DEST / "sources.cmake").write_text("\n".join(lines) + "\n")
    (DEST / "VERSION").write_text(f"{tag}\n{commit}\n")
    print(f"Vendored Luau {tag} ({commit}) into {DEST}")


if __name__ == "__main__":
    main()
